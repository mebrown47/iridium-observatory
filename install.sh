#
# install.sh — install, update or remove iridium-observatory on this machine:
# the iridium-sniffer receiver (web map on :8888) and the Observatory
# dashboards (:8890), as systemd services that start at boot.
#
# Usage (from the repo checkout, as your normal user — it sudo's as needed):
#     ./install.sh                 first install (asks a few questions)
#     ./install.sh --update        git pull, rebuild, test, reinstall, restart
#     ./install.sh --reconfigure   ask the questions again, then reinstall
#     ./install.sh --uninstall     remove services and program files
#
# Options:
#     --yes          don't ask; take the defaults (or the existing config)
#     --no-deps      skip installing packages (you've done it yourself)
#     --dry-run      print what would be done as root, change nothing
#     -h, --help     show this help
#
# Where things go:
#     /opt/iridium-observatory/        program files (binary, data, observatory)
#     /etc/iridium-observatory.conf    your settings — edit this, not the units
#     /var/lib/iridium-observatory/    archive/ (JSONL) and observatory.db
#
# Re-running is safe. Settings, archive and database survive updates and
# uninstall.
#
set -euo pipefail

# ---- pretty output ----------------------------------------------------------
if [ -t 1 ]; then B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; Z=$'\033[0m'
else B=""; G=""; Y=""; R=""; Z=""; fi
say()  { printf '%s\n' "$*"; }
info() { printf '\n%s==>%s %s\n' "$B" "$Z" "$*"; }
ok()   { printf '  %sok%s   %s\n' "$G" "$Z" "$*"; }
warn() { printf '  %swarn%s %s\n' "$Y" "$Z" "$*"; }
die()  { printf '  %serror%s %s\n' "$R" "$Z" "$*" >&2; exit 1; }

# ---- fixed locations --------------------------------------------------------
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="$REPO_ROOT/build-install"
PREFIX=/opt/iridium-observatory
CONF=/etc/iridium-observatory.conf
DATA_DIR=/var/lib/iridium-observatory
ARCHIVE_DIR="$DATA_DIR/archive"
DB_PATH="$DATA_DIR/observatory.db"
UNIT=/etc/systemd/system/iridium-sniffer.service
MARKER="# Generated by iridium-observatory install.sh"
LIBACARS_TAG=v2.2.1

# ---- args -------------------------------------------------------------------
MODE=install; ASSUME_YES=0; DEPS=1; DRY_RUN=0; PULLED=0
ORIG_ARGS=("$@")
while [ $# -gt 0 ]; do
  case "$1" in
    --update)      MODE=update;;
    --reconfigure) MODE=reconfigure;;
    --uninstall)   MODE=uninstall;;
    --yes|-y)      ASSUME_YES=1;;
    --no-deps)     DEPS=0;;
    --dry-run)     DRY_RUN=1;;
    --pulled)      PULLED=1;;   # internal: --update re-running the new script
    -h|--help)     sed -n '2,29p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0;;
    *) die "unknown option: $1 (try --help)";;
  esac
  shift
done

# ---- helpers ----------------------------------------------------------------
# Everything that changes the system outside the checkout goes through as_root,
# so --dry-run can show it without doing it.
as_root() {
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s %s\n' "$Y" "$Z" "$*"; return 0; fi
  sudo "$@"
}
# Write stdin to a root-owned file (mode $2).
root_write() {
  local dst="$1" mode="$2" tmp
  tmp="$(mktemp)"; cat > "$tmp"
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '  %s[dry-run]%s write %s:\n' "$Y" "$Z" "$dst"; sed 's/^/      | /' "$tmp"
  else
    sudo install -m "$mode" "$tmp" "$dst"
  fi
  rm -f "$tmp"
}
# Ask a question on the terminal; $2 is the default. --yes takes the default.
ask() {
  local q="$1" def="$2" ans
  if [ "$ASSUME_YES" -eq 1 ] || [ ! -r /dev/tty ]; then printf '%s' "$def"; return; fi
  printf '  %s [%s]: ' "$q" "$def" > /dev/tty
  read -r ans < /dev/tty || ans=""
  printf '%s' "${ans:-$def}"
}
yes_no() { case "$(ask "$1 (y/n)" "$2")" in [Yy]*) return 0;; *) return 1;; esac; }
have() { command -v "$1" >/dev/null 2>&1; }

# ---- preflight --------------------------------------------------------------
info "Preflight"
[ "$(uname -s)" = Linux ] || die "Linux only"
[ "$(id -u)" -ne 0 ] || die "run as your normal user, not root — it uses sudo when it needs to"
have systemctl || die "systemd is required"
have sudo || die "sudo is required"
if [ "$DRY_RUN" -eq 0 ]; then
  sudo -v || die "sudo failed"
fi
RUN_USER="$(id -un)"
ok "user: $RUN_USER   arch: $(uname -m)   $(. /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-unknown OS}")"

# ---- uninstall --------------------------------------------------------------
if [ "$MODE" = uninstall ]; then
  info "Removing services and program files"
  as_root systemctl disable --now iridium-sniffer.service 2>/dev/null || true
  if [ -x "$PREFIX/observatory/install_observatory.sh" ]; then
    if [ "$DRY_RUN" -eq 1 ]; then as_root "$PREFIX/observatory/install_observatory.sh" --uninstall
    else "$PREFIX/observatory/install_observatory.sh" --uninstall; fi
  fi
  as_root rm -f "$UNIT" /usr/local/bin/iridium-sniffer
  as_root rm -rf "$PREFIX"
  as_root systemctl daemon-reload
  ok "removed. Kept: $CONF and $DATA_DIR (delete by hand for a clean slate)"
  exit 0
fi

# ---- update: pull first, so everything below builds the new source ----------
if [ "$MODE" = update ] && [ "$PULLED" -eq 0 ]; then
  [ -f "$CONF" ] || die "no $CONF — run ./install.sh first"
  info "Updating the checkout"
  have git || die "git not found"
  git -C "$REPO_ROOT" pull --ff-only \
    || die "git pull failed (local changes or a diverged branch?) — fix the checkout and re-run"
  ok "now at $(git -C "$REPO_ROOT" describe --always --dirty --tags)"
  # The pull may have changed this script; carry on with the new one.
  exec "$REPO_ROOT/install.sh" "${ORIG_ARGS[@]}" --pulled
fi

# ---- packages ---------------------------------------------------------------
# SDRs on the USB bus right now, by vendor:product.
usb_ids() { have lsusb && lsusb | awk '{print $6}' || true; }
detect_sdr_kinds() {
  local ids; ids="$(usb_ids)"
  grep -qx '1d50:6089' <<<"$ids" && echo hackrf
  grep -qx '1d50:60a1' <<<"$ids" && echo airspy
  grep -qE '^0bda:(2832|2838)$' <<<"$ids" && echo rtlsdr
  grep -qE '^(2cf0:5246|2cf0:5250|1d50:6066)$' <<<"$ids" && echo bladerf
  grep -qE '^(2500:00|3923:78)' <<<"$ids" && echo usrp
  grep -qE '^1df7:' <<<"$ids" && echo sdrplay
  return 0
}

install_libacars_from_source() {
  info "Building libacars $LIBACARS_TAG from source (no distro package)"
  local src; src="$(mktemp -d)"
  git clone -q --depth 1 --branch "$LIBACARS_TAG" https://github.com/szpajder/libacars "$src/libacars" \
    || die "could not clone libacars"
  cmake -S "$src/libacars" -B "$src/libacars/build" -DCMAKE_BUILD_TYPE=Release >/dev/null \
    && cmake --build "$src/libacars/build" -j"$(nproc)" >/dev/null \
    || die "libacars build failed"
  as_root cmake --install "$src/libacars/build" >/dev/null
  as_root ldconfig
  rm -rf "$src"
  ok "libacars $LIBACARS_TAG installed to /usr/local"
}

if [ "$DEPS" -eq 1 ]; then
  info "Packages"
  if have apt-get; then
    SDR_KINDS="$(detect_sdr_kinds | tr '\n' ' ')"
    # Needed to build at all: one apt call, and a failure stops the install.
    CORE=(build-essential cmake pkg-config git python3 curl usbutils libfftw3-dev libusb-1.0-0-dev zlib1g-dev libxml2-dev)
    # Per-SDR: each tried on its own, so one that apt can't place (a distro
    # like DragonOS shipping its own builds) costs a warning, not the install.
    SDR_PKGS=()
    for k in $SDR_KINDS; do
      case "$k" in
        hackrf)  SDR_PKGS+=(libhackrf-dev hackrf);;
        airspy)  SDR_PKGS+=(libairspy-dev airspy);;
        rtlsdr)  SDR_PKGS+=(libsoapysdr-dev soapysdr-module-rtlsdr rtl-sdr);;
        bladerf) SDR_PKGS+=(libbladerf-dev bladerf);;
        usrp)    SDR_PKGS+=(libuhd-dev uhd-host);;
        sdrplay) SDR_PKGS+=(libsoapysdr-dev)
                 warn "SDRplay: install the SDRplay API from https://www.sdrplay.com/api/ before building";;
      esac
    done
    [ -n "$SDR_KINDS" ] && ok "SDR on USB: $SDR_KINDS" \
      || { warn "no known SDR on USB — installing HackRF/Airspy/SoapySDR support; plug yours in before the config step"
           SDR_PKGS+=(libhackrf-dev libairspy-dev libsoapysdr-dev); }
    as_root apt-get install -y -q --no-install-recommends "${CORE[@]}" \
      || die "could not install the build tools — see apt's message above"
    ok "build tools installed"
    for p in $(printf '%s\n' "${SDR_PKGS[@]}" | awk '!seen[$0]++'); do
      if dpkg -s "$p" 2>/dev/null | grep -q '^Status: install ok installed'; then
        ok "$p already installed"; continue
      fi
      # A SoapySDR module may already be there under the distro's own name
      # (DragonOS: soapysdr0.8-module-rtlsdr); don't fight it.
      case "$p" in soapysdr-module-*)
        if dpkg -l "soapysdr*-${p#soapysdr-}" 2>/dev/null | grep -q '^ii'; then
          ok "$p: provided by $(dpkg -l "soapysdr*-${p#soapysdr-}" | awk '/^ii/{print $2; exit}')"; continue
        fi;;
      esac
      if as_root apt-get install -y -q --no-install-recommends "$p" >/dev/null 2>&1; then ok "$p installed"
      else warn "$p: apt couldn't install it — skipping (try: sudo apt-get install $p)"; fi
    done
    if pkg-config --exists libacars-2 2>/dev/null; then
      ok "libacars $(pkg-config --modversion libacars-2) already present"
    elif apt-cache show libacars-dev >/dev/null 2>&1; then
      as_root apt-get install -y libacars-dev
    else
      install_libacars_from_source
    fi
  else
    warn "not a Debian/Ubuntu system — install by hand: cmake, a C compiler, fftw3, libacars-2,"
    warn "python3, and your SDR's library (see README), then re-run with --no-deps"
  fi
fi

# ---- build + test -----------------------------------------------------------
info "Building"
CMAKE_FLAGS=(-DCMAKE_BUILD_TYPE=Release)
case "$(uname -m)" in
  aarch64|arm*) CMAKE_FLAGS+=(-DUSE_OPENCL=OFF);;   # Pi GPUs can't keep up; CPU path
esac
cmake -S "$REPO_ROOT" -B "$BUILD_DIR" "${CMAKE_FLAGS[@]}" > "$BUILD_DIR.log" 2>&1 \
  && cmake --build "$BUILD_DIR" -j"$(nproc)" >> "$BUILD_DIR.log" 2>&1 \
  || { tail -20 "$BUILD_DIR.log"; die "build failed — full log: $BUILD_DIR.log"; }
BIN="$BUILD_DIR/iridium-sniffer"
ok "built $BIN"
if ldd "$BIN" | grep -q libacars; then ok "libacars linked (ACARS/CPDLC/ADS-C decode on)"
else warn "built WITHOUT libacars — ARINC-622 (CPDLC/ADS-C) decode will be off"; fi

info "Testing"
SKIP_ORACLE=1 "$REPO_ROOT/tests/run_tests.sh" > "$BUILD_DIR/tests.log" 2>&1 \
  || { tail -20 "$BUILD_DIR/tests.log"; die "tests failed — not installing. Log: $BUILD_DIR/tests.log"; }
ok "$(grep '^RESULT' "$BUILD_DIR/tests.log")"

# ---- config -----------------------------------------------------------------
# Default sniffer flags for a device, by its --list interface name.
sdr_args() {
  case "$1" in
    hackrf-*)               echo "-i $1 --hackrf-lna=40 --hackrf-vga=20";;
    airspy-*)               echo "-i $1";;
    bladerf*)               echo "-i $1 --bladerf-gain=40";;
    usrp-*)                 echo "-i $1 --usrp-gain=40";;
    sdrplay-*)              echo "-i $1";;
    soapy:driver=rtlsdr*)   echo "-i $1 -r 2400000 -c 1625500000 --soapy-gain=40";;
    soapy*)                 echo "-i $1 --soapy-gain=30";;
  esac
}
# Interfaces the new binary can see, native drivers first, one per line.
list_interfaces() {
  timeout 20 "$BIN" --list 2>/dev/null | awk '
    /^  (hackrf-|airspy-|bladerf|usrp-|sdrplay-)/ { print $1; next }
    /^  soapy-[0-9]/ { drv=$2; if (drv != "audio") soapy[++n]="soapy:driver=" drv }
    END { for (i=1;i<=n;i++) print soapy[i] }' | awk '!seen[$0]++'
}
# The args of an existing hand-written iridium-sniffer unit, one per line,
# without the binary.
foreign_unit_argv() {
  systemctl show -p ExecStart iridium-sniffer.service 2>/dev/null \
    | sed -n 's/.*argv\[\]=\([^;]*\);.*/\1/p' | tr ' ' '\n' | sed '1d; /^$/d'
}
# ...minus the --web/--archive the generated unit supplies itself.
foreign_unit_args() {
  foreign_unit_argv | grep -vE '^(--web(=.*)?|--archive(=.*)?)$' | tr '\n' ' ' | sed 's/ *$//'
}
# Where that unit's --archive was writing (relative to its working directory).
foreign_archive_dir() {
  local a wd
  a="$(foreign_unit_argv | sed -n 's/^--archive=//p; s/^--archive$/archive/p' | tail -1)"
  [ -n "$a" ] || return 0
  wd="$(systemctl show -p WorkingDirectory --value iridium-sniffer.service 2>/dev/null)"
  case "$a" in /*) echo "$a";; *) echo "${wd:-/}/$a";; esac
}

if [ -f "$CONF" ] && [ "$MODE" != reconfigure ]; then
  info "Config"
  ok "keeping $CONF (./install.sh --reconfigure to redo it)"
  # shellcheck disable=SC1090
  . "$CONF"
else
  info "Config"
  WEB_PORT=8888; OBS_PORT=8890; SNIFFER_ARGS=""
  [ -f "$CONF" ] && . "$CONF"
  IMPORTED=""
  if [ -f "$UNIT" ] && ! head -1 "$UNIT" | grep -qF "$MARKER"; then
    IMPORTED="$(foreign_unit_args)"
    [ -n "$IMPORTED" ] && say "  Found an existing iridium-sniffer service running:  $IMPORTED"
  fi
  if [ -n "$IMPORTED" ] && yes_no "Keep those settings" y; then
    SNIFFER_ARGS="$IMPORTED"
  else
    mapfile -t IFACES < <(list_interfaces)
    if [ "${#IFACES[@]}" -eq 0 ]; then
      warn "no SDR found. Plug it in and run ./install.sh --reconfigure"
      warn "(the sniffer service is installed but won't capture until then)"
      SDR=""
    else
      say "  SDRs found:"
      for i in "${!IFACES[@]}"; do say "    $((i+1))) ${IFACES[$i]}"; done
      n="$(ask "Which one" 1)"
      [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -ge 1 ] && [ "$n" -le "${#IFACES[@]}" ] || n=1
      SDR="$(sdr_args "${IFACES[$((n-1))]}")"
    fi
    SNIFFER_ARGS="$SDR --acars"
    yes_no "Power an LNA through the SDR's bias tee" n && SNIFFER_ARGS+=" -B"
    yes_no "Estimate this receiver's position from Doppler" y && SNIFFER_ARGS+=" --position"
    if yes_no "Feed ACARS to airframes.io" n; then
      SNIFFER_ARGS+=" --feed"
      st="$(ask "Station ID for airframes.io (blank for none)" "")"
      [ -n "$st" ] && SNIFFER_ARGS+=" --station=$st"
    fi
  fi
  SNIFFER_ARGS="$(echo "$SNIFFER_ARGS" | sed 's/^ *//; s/  */ /g')"
  root_write "$CONF" 0644 <<EOF
# iridium-observatory settings — written by install.sh, yours to edit.
# After changing anything:   sudo systemctl restart iridium-sniffer
# Ports or user changed?     re-run ./install.sh so the dashboards follow.
# All options:               iridium-sniffer --help
#
# Archive and database always live in $DATA_DIR

# Who the services run as.
RUN_USER="$RUN_USER"

# Receiver flags (SDR, gains, feeds). --web and --archive are added for you.
SNIFFER_ARGS="$SNIFFER_ARGS"

# Live web map port, and Observatory dashboard port.
WEB_PORT="$WEB_PORT"
OBS_PORT="$OBS_PORT"
EOF
  ok "wrote $CONF"
fi
: "${WEB_PORT:=8888}" "${OBS_PORT:=8890}" "${RUN_USER:=$(id -un)}"

# ---- install files ----------------------------------------------------------
info "Installing program files to $PREFIX"
STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/bin" "$STAGE/data" "$STAGE/observatory"
cp "$BIN" "$STAGE/bin/"
for p in "$BUILD_DIR"/libiridium-sniffer-gpu.*; do [ -e "$p" ] && cp "$p" "$STAGE/bin/"; done
cp "$REPO_ROOT/data/waypoints.csv" "$STAGE/data/"
cp "$REPO_ROOT"/observatory/*.py "$REPO_ROOT/observatory/install_observatory.sh" "$STAGE/observatory/"
git -C "$REPO_ROOT" describe --always --dirty --tags > "$STAGE/VERSION" 2>/dev/null || echo unknown > "$STAGE/VERSION"
# Swap the whole tree in by rename, so the services never see half a copy.
as_root mkdir -p "$(dirname "$PREFIX")"
as_root rm -rf "$PREFIX.new" "$PREFIX.old"
as_root cp -r "$STAGE" "$PREFIX.new"
as_root chmod -R a+rX "$PREFIX.new"
if [ "$DRY_RUN" -eq 1 ] || [ -d "$PREFIX" ]; then as_root mv "$PREFIX" "$PREFIX.old"; fi
as_root mv "$PREFIX.new" "$PREFIX"
as_root rm -rf "$PREFIX.old"
as_root ln -sf "$PREFIX/bin/iridium-sniffer" /usr/local/bin/iridium-sniffer
ok "version $(cat "$STAGE/VERSION")"

as_root mkdir -p "$ARCHIVE_DIR"
as_root chown -R "$RUN_USER:" "$DATA_DIR"
ok "data in $DATA_DIR"

# ---- sniffer service --------------------------------------------------------
info "Sniffer service"
if [ -f "$UNIT" ] && ! head -1 "$UNIT" | grep -qF "$MARKER"; then
  OLD_ARCHIVE="$(foreign_archive_dir)"
  if [ -n "$OLD_ARCHIVE" ] && [ "$OLD_ARCHIVE" != "$ARCHIVE_DIR" ] \
     && ls "$OLD_ARCHIVE"/iridium-*.jsonl >/dev/null 2>&1; then
    say "  The old service was archiving to $OLD_ARCHIVE ($(ls "$OLD_ARCHIVE"/iridium-*.jsonl | wc -l) days)."
    if yes_no "Copy that history into $ARCHIVE_DIR" y; then
      as_root systemctl stop iridium-sniffer.service
      as_root cp -n -p "$OLD_ARCHIVE"/iridium-*.jsonl "$ARCHIVE_DIR/"
      as_root chown -R "$RUN_USER:" "$ARCHIVE_DIR"
      ok "history copied (the originals are left where they were)"
    fi
  fi
  BAK="$DATA_DIR/iridium-sniffer.service.$(date +%Y%m%d-%H%M%S)"
  as_root cp "$UNIT" "$BAK"
  warn "replacing a hand-written $UNIT (saved a copy as $BAK)"
fi
GROUPS_LINE=""
getent group plugdev >/dev/null 2>&1 && GROUPS_LINE="SupplementaryGroups=plugdev"
root_write "$UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=iridium-observatory receiver (iridium-sniffer, web map)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
$GROUPS_LINE
EnvironmentFile=$CONF
WorkingDirectory=$DATA_DIR
ExecStart=$PREFIX/bin/iridium-sniffer \$SNIFFER_ARGS --web=\${WEB_PORT} --archive=$ARCHIVE_DIR
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
as_root systemctl daemon-reload
as_root systemctl enable iridium-sniffer.service
if grep -qE '(^| )(-i|--interface)[ =]' <<<" $SNIFFER_ARGS"; then
  as_root systemctl restart iridium-sniffer.service
  ok "iridium-sniffer enabled and (re)started"
else
  as_root systemctl stop iridium-sniffer.service 2>/dev/null || true
  warn "no SDR in SNIFFER_ARGS — not starting the receiver. Plug it in, then ./install.sh --reconfigure"
  NO_SDR=1
fi

# ---- observatory ------------------------------------------------------------
info "Observatory"
OBS_ARGS=(--user "$RUN_USER" --port "$OBS_PORT" --archive "$ARCHIVE_DIR" --db "$DB_PATH"
          --sniffer "http://127.0.0.1:$WEB_PORT")
if [ "$DRY_RUN" -eq 1 ]; then as_root "$PREFIX/observatory/install_observatory.sh" "${OBS_ARGS[@]}"
else "$PREFIX/observatory/install_observatory.sh" "${OBS_ARGS[@]}" | sed 's/^/  | /'; fi
as_root systemctl restart observatory-trends.service

# ---- health -----------------------------------------------------------------
info "Checking"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"; IP="${IP:-localhost}"
if [ "$DRY_RUN" -eq 1 ]; then
  ok "dry run — nothing was changed"
elif [ "${NO_SDR:-0}" -eq 1 ]; then
  warn "receiver not started (no SDR configured)"
else
  up=0
  for _ in $(seq 1 20); do
    if curl -fs -o /dev/null "http://127.0.0.1:$WEB_PORT/"; then up=1; break; fi
    sleep 1
  done
  if [ "$up" -eq 1 ]; then ok "web map answering on :$WEB_PORT"
  else
    warn "web map not answering on :$WEB_PORT yet — recent log:"
    journalctl -u iridium-sniffer -n 15 --no-pager 2>/dev/null | sed 's/^/      /' || true
  fi
  curl -fs "http://127.0.0.1:$OBS_PORT/healthz" >/dev/null && ok "observatory answering on :$OBS_PORT" \
    || warn "observatory not answering on :$OBS_PORT — journalctl -u observatory-trends"
fi

info "Done"
say "  Live map:     ${B}http://$IP:$WEB_PORT/${Z}"
say "  Observatory:  ${B}http://$IP:$OBS_PORT/${Z}   (fills in after the first 5-minute rollup)"
say "  Settings:     $CONF  then  sudo systemctl restart iridium-sniffer"
say "  Logs:         journalctl -u iridium-sniffer -f"
say "  Update:       ./install.sh --update"
if have ufw && [ "$DRY_RUN" -eq 0 ] && sudo ufw status 2>/dev/null | grep -q '^Status: active'; then
  warn "ufw is active — for LAN access:  sudo ufw allow $WEB_PORT/tcp && sudo ufw allow $OBS_PORT/tcp"
fi
